#!/usr/bin/env node

/**
 * Truth surfaces (TIN-161).
 *
 * Two static surfaces in this repo claimed to describe the build and lied
 * quietly as the build moved underneath them:
 *
 *  - `THIRD-PARTY-LICENSES.md` was hand-maintained. By 2026-08-28 it listed
 *    `shiki 3.22.0` (actual 4.2.0), `vite 6.4.1` (actual 8.0.14),
 *    `svelte 5.50.1` (actual 5.55.4), `sharp 0.33.5` (actual 0.34.5),
 *    `mermaid` as a RUNTIME dependency it no longer is, and omitted roughly
 *    two thirds of the direct dependency set. Nothing failed, because nothing
 *    checked.
 *  - `docs/build-metrics.md` was captured once on 2026-02-11 against Vite
 *    6.4.1 on a branch that no longer exists, and was titled "Baseline" with
 *    no marker saying the tree it measured is gone.
 *
 * The fix is not a fresher hand-edit. It is to derive the license surface from
 * a checked-in machine-readable source and to make staleness FAIL rather than
 * accumulate.
 *
 * Derivation source: `package-lock.json` (npm lockfile v3). It is current with
 * `package.json` and with the pnpm resolutions, and — unlike `pnpm-lock.yaml`
 * — it carries a `license` field per package. Every figure this module emits
 * comes from there; nothing is inferred, and a dependency whose lockfile entry
 * declares no license is printed as UNDECLARED rather than guessed.
 *
 * Deliberately dependency-free so it runs under plain node, without an install
 * step, in a pre-commit hook, in CI, or from the vitest suite.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const LICENSES_DOC = 'THIRD-PARTY-LICENSES.md';
export const BUILD_METRICS_DOC = 'docs/build-metrics.md';
export const GENERATED_MARKER = '<!-- generated by scripts/truth-surfaces.mjs -- do not hand-edit -->';

/** Toolchain packages `docs/build-metrics.md` must name at capture time. */
export const BUILD_METRICS_TOOLCHAIN = ['vite', 'svelte', '@sveltejs/kit'];

const readJson = (root, relative) => JSON.parse(readFileSync(join(root, relative), 'utf-8'));

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Direct dependencies with the version and license the lockfile actually
 * resolved, split into the two groups the document publishes.
 */
export function buildLicenseInventory(root) {
	const manifest = readJson(root, 'package.json');
	const lock = readJson(root, 'package-lock.json');
	const entries = lock.packages ?? {};

	const collect = (group) =>
		Object.keys(manifest[group] ?? {})
			.sort()
			.map((name) => {
				const entry = entries[`node_modules/${name}`];
				return {
					name,
					specifier: manifest[group][name],
					version: entry?.version ?? 'UNRESOLVED',
					license: entry?.license ?? 'UNDECLARED',
					resolved: entry?.resolved ?? null,
				};
			});

	const thirdParty = Object.entries(entries).filter(([path]) => path.startsWith('node_modules/'));
	const histogram = new Map();
	for (const [, entry] of thirdParty) {
		const license = entry.license ?? 'UNDECLARED';
		histogram.set(license, (histogram.get(license) ?? 0) + 1);
	}

	return {
		runtime: collect('dependencies'),
		build: collect('devDependencies'),
		resolvedPackageCount: thirdParty.length,
		licenseHistogram: [...histogram.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])),
		undeclared: thirdParty
			.filter(([, entry]) => entry.license === undefined)
			.map(([path]) => path.replace(/^node_modules\//, ''))
			.sort(),
	};
}

const row = ({ name, specifier, version, license }) => `| ${name} | \`${specifier}\` | ${version} | ${license} |`;

const table = (rows) =>
	['| Package | Declared | Resolved | License |', '| --- | --- | --- | --- |', ...rows.map(row)].join('\n');

/** Render the whole document. Pure: same inventory in, same bytes out. */
export function renderLicensesDoc(inventory) {
	const histogram = inventory.licenseHistogram
		.map(([license, count]) => `| ${license} | ${count} |`)
		.join('\n');

	return `# Third-Party Licenses

${GENERATED_MARKER}

This project (transscendsurvival.org) is dedicated to the public domain under
[CC0 1.0 Universal](https://creativecommons.org/publicdomain/zero/1.0/).

Every figure below is derived from \`package-lock.json\` — the package name and
its declared range from \`package.json\`, the resolved version and the license
string from the lockfile entry for that exact resolution. Nothing here is
hand-entered, so nothing here can drift without \`scripts/truth-surfaces.test.mts\`
failing.

Regenerate with:

\`\`\`sh
node scripts/truth-surfaces.mjs --write
\`\`\`

A dependency whose lockfile entry declares no license is printed as
\`UNDECLARED\`. It is never guessed from the package name, the organisation, or
a sibling version.

The previous revision of this file was hand-maintained and had drifted: it
listed \`shiki 3.22.0\`, \`vite 6.4.1\`, \`svelte 5.50.1\` and \`sharp 0.33.5\`
against resolutions of 4.2.0, 8.0.14, 5.55.4 and 0.34.5, carried \`mermaid\` as
a runtime dependency it no longer is, and omitted most of the direct set.

## Runtime Dependencies

${table(inventory.runtime)}

## Build / Dev Dependencies

${table(inventory.build)}

## Full Resolved Tree

${inventory.resolvedPackageCount} third-party packages are resolved into the
lockfile in total (direct and transitive). Their declared licenses:

| License | Packages |
| --- | --- |
${histogram}

${
	inventory.undeclared.length === 0
		? 'Every resolved package declares a license.'
		: `${inventory.undeclared.length} resolved package(s) declare no license field in the lockfile:\n\n${inventory.undeclared
				.map((name) => `- \`${name}\``)
				.join('\n')}\n\nWorkspace-local packages are covered by this repository's CC0 dedication; any\nother name on that list is an unreviewed license and is a follow-up, not a\nsilent MIT.`
}
`;
}

/** Metadata `docs/build-metrics.md` must declare about its own capture. */
export function readBuildMetricsHeader(root) {
	const body = readFileSync(join(root, BUILD_METRICS_DOC), 'utf-8');
	const field = (label) => {
		const match = body.match(new RegExp(`^- \\*\\*${label}:\\*\\* (.+)$`, 'm'));
		return match ? match[1].trim() : null;
	};
	const toolchain = {};
	for (const name of BUILD_METRICS_TOOLCHAIN) {
		const match = body.match(new RegExp(`^\\| \`${escapeRegExp(name)}\` \\| ([^|]+) \\|`, 'm'));
		toolchain[name] = match ? match[1].trim() : null;
	}
	return { body, status: field('Status'), capturedAt: field('Captured'), toolchain };
}

/**
 * The freshness rule, stated so it can fail in both directions:
 *
 *  - the document must declare a Status, a capture date, and the version of
 *    every toolchain package it was captured against;
 *  - if any of those versions is not what `package.json` declares today, the
 *    Status must say STALE. Bumping vite without recapturing turns the page
 *    red; recapturing on the current toolchain and updating the versions lets
 *    it go green again.
 */
export function checkBuildMetricsFreshness(root) {
	const violations = [];
	const manifest = readJson(root, 'package.json');
	const declared = { ...manifest.dependencies, ...manifest.devDependencies };
	const { status, capturedAt, toolchain } = readBuildMetricsHeader(root);

	if (!status) violations.push(`${BUILD_METRICS_DOC}: no "- **Status:** ..." line.`);
	if (!capturedAt) violations.push(`${BUILD_METRICS_DOC}: no "- **Captured:** ..." line.`);

	const drifted = [];
	for (const name of BUILD_METRICS_TOOLCHAIN) {
		const capturedVersion = toolchain[name];
		if (!capturedVersion) {
			violations.push(
				`${BUILD_METRICS_DOC}: does not record the \`${name}\` version it was captured against. ` +
					'A metrics page that will not say which toolchain produced it cannot be checked for staleness.',
			);
			continue;
		}
		if (capturedVersion !== declared[name]) {
			drifted.push(
				`${name} captured at ${capturedVersion}, package.json ` +
					(declared[name] === undefined ? 'no longer declares it' : `declares ${declared[name]}`),
			);
		}
	}

	if (drifted.length > 0 && !/STALE/.test(status ?? '')) {
		violations.push(
			`${BUILD_METRICS_DOC}: the toolchain moved (${drifted.join('; ')}) but Status does not say STALE. ` +
				'Either recapture the metrics against the current toolchain and update the recorded versions, ' +
				'or mark the page STALE — it may not keep presenting itself as current.',
		);
	}
	if (drifted.length === 0 && /STALE/.test(status ?? '')) {
		violations.push(
			`${BUILD_METRICS_DOC}: Status says STALE but the recorded toolchain matches package.json. ` +
				'Drop the marker rather than leaving a permanent warning nobody reads.',
		);
	}

	return violations;
}

/** Everything, as a violation list. Empty means both surfaces are truthful. */
export function checkTruthSurfaces(root) {
	const violations = [];
	const expected = renderLicensesDoc(buildLicenseInventory(root));
	const actual = readFileSync(join(root, LICENSES_DOC), 'utf-8');
	if (actual !== expected) {
		violations.push(
			`${LICENSES_DOC} is out of date with package-lock.json. ` +
				'Run `node scripts/truth-surfaces.mjs --write`.',
		);
	}
	violations.push(...checkBuildMetricsFreshness(root));
	return violations;
}

/* CLI: `--write` regenerates the license doc; no flag checks both surfaces. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const root = process.cwd();
	if (process.argv.includes('--write')) {
		const { writeFileSync } = await import('node:fs');
		writeFileSync(join(root, LICENSES_DOC), renderLicensesDoc(buildLicenseInventory(root)));
		process.stdout.write(`wrote ${LICENSES_DOC}\n`);
	} else {
		const violations = checkTruthSurfaces(root);
		if (violations.length === 0) {
			process.stdout.write('truth surfaces OK\n');
		} else {
			for (const violation of violations) process.stderr.write(`- ${violation}\n`);
			process.exitCode = 1;
		}
	}
}
