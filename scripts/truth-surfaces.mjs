#!/usr/bin/env node

/**
 * Truth surfaces (TIN-161).
 *
 * Three static surfaces in this repo claimed to describe the build and lied
 * quietly as the build moved underneath them:
 *
 *  - `THIRD-PARTY-LICENSES.md` was hand-maintained. By 2026-08-28 it listed
 *    `shiki 3.22.0` (actual 4.2.0), `vite 6.4.1` (actual 8.0.14),
 *    `svelte 5.50.1` (actual 5.55.4), `sharp 0.33.5` (actual 0.34.5),
 *    `mermaid` as a RUNTIME dependency it no longer is, and omitted roughly
 *    two thirds of the direct dependency set. Nothing failed, because nothing
 *    checked.
 *  - `src/routes/THIRD-PARTY-LICENSES/+page.svelte` is the copy the public
 *    actually reads — it is prerendered and linked from the site footer — and
 *    it carried the same drift plus a "243 production packages" summary that
 *    understated Apache-2.0 by two orders of magnitude. Regenerating only the
 *    Markdown would have left the published page lying, so the page is now
 *    rendered from `src/lib/data/third-party-licenses.json`, which this module
 *    generates and byte-compares alongside the Markdown.
 *  - `docs/build-metrics.md` was captured once on 2026-02-11 against Vite
 *    6.4.1 on a branch that no longer exists, and was titled "Baseline" with
 *    no marker saying the tree it measured is gone.
 *
 * The fix is not a fresher hand-edit. It is to derive the license surfaces
 * from a checked-in machine-readable source and to make staleness FAIL rather
 * than accumulate.
 *
 * Derivation source: `package-lock.json` (npm lockfile v3). It is current with
 * `package.json` and with the pnpm resolutions, and — unlike `pnpm-lock.yaml`
 * — it carries a `license` field per package. Every figure this module emits
 * comes from there; nothing is inferred, and a dependency whose lockfile entry
 * declares no license is printed as UNDECLARED rather than guessed.
 *
 * Deliberately dependency-free so it runs under plain node, without an install
 * step, in a pre-commit hook, in CI, or from the vitest suite. The one
 * exception is the provenance check, which shells out to `git` and is
 * therefore only run where a `.git` directory exists; CI runs this module at
 * the repository root for exactly that reason.
 */

import { existsSync, readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

export const LICENSES_DOC = 'THIRD-PARTY-LICENSES.md';
export const LICENSES_DATA = 'src/lib/data/third-party-licenses.json';
export const BUILD_METRICS_DOC = 'docs/build-metrics.md';
export const GENERATED_MARKER = '<!-- generated by scripts/truth-surfaces.mjs -- do not hand-edit -->';

/** Toolchain packages `docs/build-metrics.md` must name at capture time. */
export const BUILD_METRICS_TOOLCHAIN = ['vite', 'svelte', '@sveltejs/kit'];

/**
 * Every manifest key that declares a direct dependency. All four are read even
 * though this repository currently uses two: a surface that silently ignores
 * `optionalDependencies` would publish an incomplete attribution the first time
 * one was added, and nothing would say so.
 */
export const DEPENDENCY_GROUPS = [
	{ key: 'dependencies', field: 'runtime', heading: 'Runtime Dependencies' },
	{ key: 'devDependencies', field: 'build', heading: 'Build / Dev Dependencies' },
	{ key: 'optionalDependencies', field: 'optional', heading: 'Optional Dependencies' },
	{ key: 'peerDependencies', field: 'peer', heading: 'Peer Dependencies' },
];

const readJson = (root, relative) => JSON.parse(readFileSync(join(root, relative), 'utf-8'));

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

const NODE_MODULES = 'node_modules/';

/** `node_modules/a/node_modules/@s/b` is an install of `@s/b`, not of `a`. */
const packageNameFromInstallPath = (path) => path.slice(path.lastIndexOf(NODE_MODULES) + NODE_MODULES.length);

const histogram = (packages) => {
	const counts = new Map();
	for (const { license } of packages) {
		const key = license ?? 'UNDECLARED';
		counts.set(key, (counts.get(key) ?? 0) + 1);
	}
	return [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
};

/**
 * Direct dependencies with the version and license the lockfile actually
 * resolved, plus honest aggregate figures for the resolved tree.
 *
 * `lock.packages` is keyed by INSTALL PATH, not by package: a package that npm
 * cannot hoist to the root is recorded once per place it lands
 * (`@opentelemetry/core` has 21 such entries here). Counting keys therefore
 * overstates the package count, so the tree figures deduplicate on
 * `name@version` and drop workspace links, which are this repository's own code
 * and carry neither a version nor a license.
 */
export function buildLicenseInventory(root) {
	const manifest = readJson(root, 'package.json');
	const lock = readJson(root, 'package-lock.json');
	const entries = lock.packages ?? {};

	const groups = DEPENDENCY_GROUPS.map(({ key, field, heading }) => ({
		key,
		field,
		heading,
		rows: Object.keys(manifest[key] ?? {})
			.sort()
			.map((name) => {
				const entry = entries[`${NODE_MODULES}${name}`];
				return {
					name,
					specifier: manifest[key][name],
					version: entry?.version ?? 'UNRESOLVED',
					license: entry?.license ?? 'UNDECLARED',
					resolved: entry?.resolved ?? null,
				};
			}),
	})).filter((group) => group.rows.length > 0);

	const installs = Object.entries(entries).filter(([path]) => path.startsWith(NODE_MODULES));
	const packages = new Map();
	for (const [path, entry] of installs) {
		const name = packageNameFromInstallPath(path);
		const key = `${name}@${entry.version ?? 'UNRESOLVED'}`;
		const existing = packages.get(key);
		if (!existing) {
			packages.set(key, {
				name,
				version: entry.version ?? null,
				license: entry.license ?? null,
				link: entry.link === true,
				dev: entry.dev === true,
			});
			continue;
		}
		// One package installed in several places is still one package, and it
		// is a runtime package if ANY of those installs is outside the dev tree.
		existing.dev = existing.dev && entry.dev === true;
		existing.license ??= entry.license ?? null;
	}

	const resolved = [...packages.values()];
	const thirdParty = resolved.filter((entry) => !entry.link);
	const workspace = resolved.filter((entry) => entry.link);
	const runtime = thirdParty.filter((entry) => !entry.dev);

	return {
		groups,
		...Object.fromEntries(groups.map((group) => [group.field, group.rows])),
		tree: {
			installCount: installs.length,
			packageCount: thirdParty.length,
			runtimePackageCount: runtime.length,
			licenseHistogram: histogram(thirdParty),
			runtimeLicenseHistogram: histogram(runtime),
			undeclared: thirdParty
				.filter((entry) => entry.license === null)
				.map((entry) => `${entry.name}@${entry.version}`)
				.sort(),
			workspacePackages: workspace.map((entry) => entry.name).sort(),
		},
	};
}

const row = ({ name, specifier, version, license, resolved }) =>
	`| ${name} | \`${specifier}\` | ${version} | ${license} | ${resolved ? `<${resolved}>` : '—'} |`;

const table = (rows) =>
	[
		'| Package | Declared | Resolved | License | Source |',
		'| --- | --- | --- | --- | --- |',
		...rows.map(row),
	].join('\n');

const histogramTable = (counts) =>
	['| License | Packages |', '| --- | --- |', ...counts.map(([license, count]) => `| ${license} | ${count} |`)].join(
		'\n',
	);

/** Render the whole document. Pure: same inventory in, same bytes out. */
export function renderLicensesDoc(inventory) {
	const { tree } = inventory;
	const sections = inventory.groups.map((group) => `## ${group.heading}\n\n${table(group.rows)}`).join('\n\n');

	const undeclaredSection =
		tree.undeclared.length === 0
			? 'Every resolved third-party package declares a license.'
			: `${tree.undeclared.length} resolved third-party package(s) declare no license field in the lockfile:\n\n${tree.undeclared
					.map((name) => `- \`${name}\``)
					.join('\n')}\n\nEach one is an unreviewed license and a follow-up, not a silent MIT.`;

	const workspaceSection =
		tree.workspacePackages.length === 0
			? ''
			: `\nThe lockfile also carries ${tree.workspacePackages.length} workspace link(s) — ${tree.workspacePackages
					.map((name) => `\`${name}\``)
					.join(
						', ',
					)} — which are this repository's own code under its CC0 dedication. They are not third party and are excluded from every figure above.\n`;

	return `# Third-Party Licenses

${GENERATED_MARKER}

This project (transscendsurvival.org) is dedicated to the public domain under
[CC0 1.0 Universal](https://creativecommons.org/publicdomain/zero/1.0/).

Every figure below is derived from \`package-lock.json\` — the package name and
its declared range from \`package.json\`, the resolved version, license string
and source URL from the lockfile entry for that exact resolution. Nothing here
is hand-entered, so nothing here can drift without \`scripts/truth-surfaces.mjs\`
failing.

Regenerate with:

\`\`\`sh
node scripts/truth-surfaces.mjs --write
\`\`\`

That command writes this file and \`${LICENSES_DATA}\`, which
\`src/routes/THIRD-PARTY-LICENSES/+page.svelte\` renders — the published page and
this document are the same data, so they cannot disagree.

A dependency whose lockfile entry declares no license is printed as
\`UNDECLARED\`. It is never guessed from the package name, the organisation, or
a sibling version.

The previous revision of this file was hand-maintained and had drifted: it
listed \`shiki 3.22.0\`, \`vite 6.4.1\`, \`svelte 5.50.1\` and \`sharp 0.33.5\`
against resolutions of 4.2.0, 8.0.14, 5.55.4 and 0.34.5, carried \`mermaid\` as
a runtime dependency it no longer is, and omitted most of the direct set.

${sections}

## Resolved Tree

\`package-lock.json\` records ${tree.installCount} installs under \`node_modules/\`.
That is a count of install paths, not of packages: npm records a package once
per place it lands, so a dependency it cannot hoist appears many times over.
Deduplicated on \`name@version\`, the tree is **${tree.packageCount}** distinct
third-party packages, of which **${tree.runtimePackageCount}** are reachable
outside \`devDependencies\`.

### Runtime Packages

This is the set that governs attribution: the site is a prerendered static
build, so only these licenses travel to a reader.

${histogramTable(tree.runtimeLicenseHistogram)}

### Full Resolved Tree

Development-only packages included. Licenses appearing here but not above are
build-time only and are not distributed.

${histogramTable(tree.licenseHistogram)}

## Undeclared Licenses

${undeclaredSection}
${workspaceSection}`;
}

/**
 * The same inventory as JSON, for the prerendered route. Written by `--write`
 * and byte-compared by `checkTruthSurfaces`, so the published page is covered
 * by the same guard as the Markdown.
 */
export function renderLicensesData(inventory) {
	return `${JSON.stringify(
		{
			generatedBy: 'scripts/truth-surfaces.mjs',
			source: 'package-lock.json',
			groups: inventory.groups.map(({ key, heading, rows }) => ({ key, heading, rows })),
			tree: inventory.tree,
		},
		null,
		'\t',
	)}\n`;
}

/** Metadata `docs/build-metrics.md` must declare about its own capture. */
export function readBuildMetricsHeader(root) {
	const body = readFileSync(join(root, BUILD_METRICS_DOC), 'utf-8');
	const field = (label) => {
		const match = body.match(new RegExp(`^- \\*\\*${label}:\\*\\* (.+)$`, 'm'));
		return match ? match[1].trim() : null;
	};
	const toolchain = {};
	for (const name of BUILD_METRICS_TOOLCHAIN) {
		const match = body.match(new RegExp(`^\\| \`${escapeRegExp(name)}\` \\| ([^|]+) \\|`, 'm'));
		toolchain[name] = match ? match[1].trim() : null;
	}
	const commit = body.match(/^- \*\*Captured:\*\* .*\(commit `([0-9a-f]{7,40})`\)/m);
	return {
		body,
		status: field('Status'),
		capturedAt: field('Captured'),
		captureCommit: commit ? commit[1] : null,
		toolchain,
	};
}

/**
 * The freshness rule, stated so it can fail in both directions:
 *
 *  - the document must declare a Status, a capture date, and the version of
 *    every toolchain package it was captured against;
 *  - if any of those versions is not what `package.json` declares today, the
 *    Status must say STALE. Bumping vite without recapturing turns the page
 *    red; recapturing on the current toolchain and updating the versions lets
 *    it go green again.
 *
 * On its own this checks the label rather than the measurement, which is why
 * `checkBuildMetricsProvenance` exists: without it the cheapest way to green is
 * to retype the toolchain row, and the guard would reward falsifying the one
 * part of the page that records historical fact.
 */
export function checkBuildMetricsFreshness(root) {
	if (!existsSync(join(root, BUILD_METRICS_DOC))) {
		return [`${BUILD_METRICS_DOC}: missing. The build metrics surface may not be deleted to silence its check.`];
	}

	const violations = [];
	const manifest = readJson(root, 'package.json');
	const declared = { ...manifest.dependencies, ...manifest.devDependencies };
	const { status, capturedAt, toolchain } = readBuildMetricsHeader(root);

	if (!status) violations.push(`${BUILD_METRICS_DOC}: no "- **Status:** ..." line.`);
	if (!capturedAt) violations.push(`${BUILD_METRICS_DOC}: no "- **Captured:** ..." line.`);

	const drifted = [];
	for (const name of BUILD_METRICS_TOOLCHAIN) {
		const capturedVersion = toolchain[name];
		if (!capturedVersion) {
			violations.push(
				`${BUILD_METRICS_DOC}: does not record the \`${name}\` version it was captured against. ` +
					'A metrics page that will not say which toolchain produced it cannot be checked for staleness.',
			);
			continue;
		}
		if (capturedVersion !== declared[name]) {
			drifted.push(
				`${name} captured at ${capturedVersion}, package.json ` +
					(declared[name] === undefined ? 'no longer declares it' : `declares ${declared[name]}`),
			);
		}
	}

	if (drifted.length > 0 && !/STALE/.test(status ?? '')) {
		violations.push(
			`${BUILD_METRICS_DOC}: the toolchain moved (${drifted.join('; ')}) but Status does not say STALE. ` +
				'Either recapture the metrics against the current toolchain and update the recorded versions, ' +
				'or mark the page STALE — it may not keep presenting itself as current.',
		);
	}
	if (drifted.length === 0 && /STALE/.test(status ?? '')) {
		violations.push(
			`${BUILD_METRICS_DOC}: Status says STALE but the recorded toolchain matches package.json. ` +
				'Drop the marker rather than leaving a permanent warning nobody reads.',
		);
	}

	return violations;
}

/** Read `<commit>:<path>` out of the repository at `root`. */
export const gitFileReader =
	(root) =>
	(commit, path) => {
		const result = spawnSync('git', ['-C', root, 'show', `${commit}:${path}`], { encoding: 'utf-8' });
		return result.status === 0 ? result.stdout : null;
	};

/**
 * The toolchain row is provenance, not a field.
 *
 * `checkBuildMetricsFreshness` compares the recorded toolchain against
 * `package.json` today, which means the cheapest path to green after a Vite
 * bump is to retype those three cells and drop the STALE marker — without
 * recapturing a single number. That turns the guard into an incentive to
 * falsify history.
 *
 * So the row is validated against the commit the page names as its capture:
 * the recorded ranges must be what `<capture commit>:package.json` declared.
 * Editing the row now requires moving the capture commit, and moving the
 * capture commit is a claim that the measurements were retaken.
 *
 * `readAtCommit` is injected so this is testable without a git repository; the
 * default reads the real one.
 */
export function checkBuildMetricsProvenance(root, readAtCommit = gitFileReader(root)) {
	if (!existsSync(join(root, BUILD_METRICS_DOC))) {
		return [`${BUILD_METRICS_DOC}: missing. The build metrics surface may not be deleted to silence its check.`];
	}

	const { captureCommit, toolchain } = readBuildMetricsHeader(root);
	if (!captureCommit) {
		return [
			`${BUILD_METRICS_DOC}: the "- **Captured:** ..." line does not name the commit it was captured at ` +
				'(expected a trailing "(commit `<sha>`)"). Without it the toolchain table is an unverifiable claim ' +
				'that can be retyped to make the freshness check pass.',
		];
	}

	const source = readAtCommit(captureCommit, 'package.json');
	if (source === null) {
		return [
			`${BUILD_METRICS_DOC}: cannot read package.json at the declared capture commit \`${captureCommit}\`. ` +
				'The page names a commit that this repository does not have.',
		];
	}

	let declaredAtCapture;
	try {
		const parsed = JSON.parse(source);
		declaredAtCapture = { ...parsed.dependencies, ...parsed.devDependencies };
	} catch {
		return [`${BUILD_METRICS_DOC}: package.json at capture commit \`${captureCommit}\` is not valid JSON.`];
	}

	const violations = [];
	for (const name of BUILD_METRICS_TOOLCHAIN) {
		const recorded = toolchain[name];
		// A missing row is already a freshness violation; do not double-report.
		if (recorded === null) continue;
		const actual = declaredAtCapture[name];
		if (recorded !== actual) {
			violations.push(
				`${BUILD_METRICS_DOC}: records \`${name}\` at ${recorded} "at capture", but ` +
					`\`${captureCommit}:package.json\` declares ` +
					`${actual === undefined ? 'no such dependency' : actual}. ` +
					'The toolchain row is provenance — it must be what the capture commit declared. ' +
					'Recapture the metrics and name the new commit rather than editing the row.',
			);
		}
	}
	return violations;
}

/** Everything, as a violation list. Empty means every surface is truthful. */
export function checkTruthSurfaces(root) {
	const violations = [];
	const inventory = buildLicenseInventory(root);

	for (const [surface, expected] of [
		[LICENSES_DOC, renderLicensesDoc(inventory)],
		[LICENSES_DATA, renderLicensesData(inventory)],
	]) {
		const path = join(root, surface);
		if (!existsSync(path)) {
			violations.push(`${surface}: missing. Run \`node scripts/truth-surfaces.mjs --write\`.`);
			continue;
		}
		if (readFileSync(path, 'utf-8') !== expected) {
			violations.push(
				`${surface} is out of date with package-lock.json. Run \`node scripts/truth-surfaces.mjs --write\`.`,
			);
		}
	}

	violations.push(...checkBuildMetricsFreshness(root));
	// The provenance check needs git history. The Vitest sandbox is a copied
	// tree with no `.git`, so CI runs this module at the repository root as
	// well — see the "Truth surfaces" step in .github/workflows/ci.yml.
	if (existsSync(join(root, '.git'))) {
		violations.push(...checkBuildMetricsProvenance(root));
	}

	return violations;
}

/* CLI: `--write` regenerates the license surfaces; no flag checks all three. */
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	const root = process.cwd();
	if (process.argv.includes('--write')) {
		const { mkdirSync, writeFileSync } = await import('node:fs');
		const { dirname } = await import('node:path');
		const inventory = buildLicenseInventory(root);
		for (const [surface, contents] of [
			[LICENSES_DOC, renderLicensesDoc(inventory)],
			[LICENSES_DATA, renderLicensesData(inventory)],
		]) {
			mkdirSync(dirname(join(root, surface)), { recursive: true });
			writeFileSync(join(root, surface), contents);
			process.stdout.write(`wrote ${surface}\n`);
		}
	} else {
		const violations = checkTruthSurfaces(root);
		if (violations.length === 0) {
			process.stdout.write('truth surfaces OK\n');
		} else {
			for (const violation of violations) process.stderr.write(`- ${violation}\n`);
			process.exitCode = 1;
		}
	}
}
